// >>> SWISS ENGINE (generated by tools/sync-swiss-engine.sh from index.html; do not edit)
/* Swiss engine. Every new tournament runs as Swiss rounds (payload v:3,
   fmt:'swiss'). gm holds every game and grows one round at a time; a bye is
   {b:null,w:a,src:'bye'}, a draw is w:'draw', and a game given up because a
   player dropped is src:'drop' (t_forfeits on the server).
   Tournament points (Malediction Tournament Guide, January 2026): victory 3,
   bye 3, draw 2, defeat 1. Mastery differential: the winner's mastery minus
   the loser's, never below 0; 0 for a defeat or a draw; 20 for a bye and for a
   game won because the opponent dropped. Ranking: points, then mastery
   differential (both official), then strength of schedule (the opponents'
   points), then head to head, then a shared rank (Seekers League choices).
   Pure: no DOM and no globals, so the test page can load this block alone.
   The server repeats the scoring in t_sw_score and checks every pairing. */
function swRng(seed){let a=seed>>>0;return()=>{a=a+1831565813|0;let t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296}}
function swShuffle(keys,seed){const o=keys.slice(),r=swRng(seed);for(let i=o.length-1;i>0;i--){const j=Math.floor(r()*(i+1)),x=o[i];o[i]=o[j];o[j]=x}return o}
function swIsSwiss(p){return !!p&&3===p.v&&"swiss"===p.fmt}
function swCur(p){return (p&&p.gm||[]).reduce((m,g)=>Math.max(m,g.r|0),0)}
/* Rounds. The Guide's table: 4 players 2, 5-8 3, 9-16 4, 17-32 5; above 32
   is 6 and 3 players play 3 (one bye each), both Seekers League choices. More
   rounds than players-minus-one would force a rematch. The Play Network value
   is the default when it fits (1 round, when more are possible, is taken as
   the Play Network's unset default); the organizer can change it before the start. */
function swMaxRounds(n){n|=0;return Math.max(1,Math.min(15,n%2?n:n-1))}
function swRoundsFor(n){return Math.min(swMaxRounds(n),n<=3?3:n<=4?2:n<=8?3:n<=16?4:n<=32?5:6)}
function swRoundsDefault(n,pnRounds){const r=Number(pnRounds);return null!=pnRounds&&Number.isInteger(r)&&r>=Math.min(2,swMaxRounds(n))&&r<=swMaxRounds(n)?r:swRoundsFor(n)}
function swDropSet(p){return new Set((p.entrants||[]).filter(e=>e&&"drop"===e.st).map(e=>e.id))}
/* The players still in: entrants marked in, in the start order (in a draft,
   the entrants order). t_active on the server. */
function swActive(p){
  const g=(p.groups||[]).flat(),st=new Map((p.entrants||[]).filter(e=>e).map(e=>[e.id,e.st]));
  return (g.length?g:(p.entrants||[]).map(e=>e&&e.id)).filter(k=>null!=k&&"in"===st.get(k));
}
function swPk(a,b){return a<b?a+"|"+b:b+"|"+a}
/* Every pair that was ever paired (forfeits included, byes excluded). */
function swMet(p){const s=new Set;(p.gm||[]).forEach(m=>{null!=m.b&&s.add(swPk(m.a,m.b))});return s}
function swByes(p){const s=new Set;(p.gm||[]).forEach(m=>{"bye"===m.src&&s.add(m.a)});return s}
/* Mastery as the server reads it: 0..999, otherwise missing. */
function swMs(v){return null!=v&&/^[0-9]{1,3}$/.test(String(v))?+v:null}
/* One side of a decided game: [points, "w"|"d"|"l", mastery differential]. */
function swSide(m,isA){
  const me=isA?m.a:m.b;
  if("bye"===m.src)return isA?[3,"w",20]:null;
  if("draw"===m.w)return[2,"d",0];
  if(m.w!==me)return[1,"l",0];
  if("drop"===m.src)return[3,"w",20];
  const x=swMs(isA?m.sa:m.sb),y=swMs(isA?m.sb:m.sa);
  return[3,"w",null==x||null==y?0:Math.max(0,x-y)];
}
/* The standings, best first: {id,rk,tp,w,d,l,md,sos,drop,byes,mdGap,shared}.
   A shared rank keeps the round-1 order, so the order (and the pairing that
   follows it) never depends on names or on the browser's sort. */
function swTable(p){
  const gm=p.gm||[],g=(p.groups||[]).flat(),keys=g.length?g:swActive(p),D=swDropSet(p),
    rec=Object.create(null),seed=Object.create(null);
  keys.forEach(id=>{rec[id]={id,rk:0,tp:0,w:0,d:0,l:0,md:0,sos:0,drop:D.has(id),byes:0,mdGap:!1,shared:!1,opp:[]}});
  gm.forEach(m=>{
    if(null==m.w)return;
    [!0,!1].forEach(isA=>{
      const me=isA?m.a:m.b,R=null!=me&&rec[me],s=R&&swSide(m,isA);
      if(!s)return;
      R.tp+=s[0];R[s[1]]++;R.md+=s[2];
      if("bye"===m.src){R.byes++;return}
      const op=isA?m.b:m.a;null!=op&&R.opp.push(op);
      "drop"!==m.src&&"draw"!==m.w&&(null==swMs(m.sa)||null==swMs(m.sb))&&(R.mdGap=!0);
    });
  });
  keys.forEach(id=>{const R=rec[id];R.sos=R.opp.reduce((s,o)=>s+(rec[o]?rec[o].tp:0),0)});
  let n=0;
  gm.forEach(m=>{1===m.r&&[m.a,m.b].forEach(k=>{null!=k&&!(k in seed)&&(seed[k]=n++)})});
  keys.forEach(k=>{k in seed||(seed[k]=n++)});
  const rows=keys.map(k=>rec[k]),out=[];
  rows.sort((x,y)=>y.tp-x.tp||y.md-x.md||y.sos-x.sos||seed[x.id]-seed[y.id]);
  for(let i=0;i<rows.length;){
    let j=i+1;
    while(j<rows.length&&rows[j].tp===rows[i].tp&&rows[j].md===rows[i].md&&rows[j].sos===rows[i].sos)j++;
    const T=rows.slice(i,j);
    /* Head to head only settles a group in which everyone has played everyone:
       the points each earned in the games among them. */
    if(T.length>1){
      const S=new Set(T.map(r=>r.id)),h=Object.create(null),met=new Set;
      T.forEach(r=>{h[r.id]=0});
      gm.forEach(m=>{
        if(null==m.w||null==m.b||m.a===m.b||!S.has(m.a)||!S.has(m.b))return;
        met.add(swPk(m.a,m.b));h[m.a]+=swSide(m,!0)[0];h[m.b]+=swSide(m,!1)[0];
      });
      let all=!0;
      for(let x=0;all&&x<T.length;x++)for(let y=x+1;y<T.length;y++)if(!met.has(swPk(T[x].id,T[y].id))){all=!1;break}
      T.forEach(r=>{r.h2h=all?h[r.id]:0});
      all&&T.sort((x,y)=>y.h2h-x.h2h||seed[x.id]-seed[y.id]);
    }
    T.forEach(r=>out.push(r));i=j;
  }
  out.forEach((r,i)=>{const q=out[i-1];r.rk=q&&q.tp===r.tp&&q.md===r.md&&q.sos===r.sos&&(q.h2h|0)===(r.h2h|0)?q.rk:i+1});
  out.forEach((r,i)=>{r.shared=!!(out[i-1]&&out[i-1].rk===r.rk||out[i+1]&&out[i+1].rk===r.rk);delete r.opp;delete r.h2h});
  return out;
}
/* The players still in, best first: the pairing order. */
function swOrder(p){const A=new Set(swActive(p));return swTable(p).filter(r=>A.has(r.id)).map(r=>r.id)}
/* The champion tops the final standings; nobody when first place is shared.
   A dropped player is never champion. */
function swChampion(rows){const R=(rows||[]).filter(r=>r&&!r.drop),c=R[0];return c&&!R.slice(1).some(r=>r.rk===c.rk)?c.id:null}
/* t_forfeits, for the page: a player who drops loses the undecided game of
   the round (the opponent scores it like a bye); bringing them back undoes
   that forfeit. A game between two dropped players stays without a result. */
function swForfeits(p){
  const D=swDropSet(p);
  return Object.assign({},p,{gm:(p.gm||[]).map(m0=>{
    const m=Object.assign({},m0),b=null==m.b?null:m.b,da=D.has(m.a),db=null!=b&&D.has(b),
      win=da&&!db?b:db&&!da?m.a:null;
    if("drop"===m.src){
      const lose=m.w===m.a?b:null!=b&&m.w===b?m.a:null;
      if(null==lose||!D.has(lose)){delete m.src;delete m.at;delete m.auto;delete m.dx;m.w=null}
    }
    null==m.w&&null!=win&&(m.w=win,m.src="drop");
    return m;
  })});
}
/* The round is complete (t_gm_done): every game has a result, or is between
   two dropped players and will never be played. */
function swRoundDone(p){const D=swDropSet(p),g=p.gm||[];return g.length>0&&g.every(m=>null!=m.w||D.has(m.a)&&null!=m.b&&D.has(m.b))}
/* Pairs the players in `order` (best first), avoiding the pairs in `met`.
   Each player meets the closest-ranked player they have not met yet. With an
   odd count the bye goes to the lowest-ranked player without a bye (anyone,
   once everyone has had one); the next one up is tried when that bye would
   force a rematch. A rematch-free pairing is searched exhaustively within a
   budget; only when none exists (exhaustive) or none was found does it pair
   with the fewest rematches it can find. Returns {pairs:[[a,b|null]] (table
   order, the bye last), bye, rematches, exhaustive}. Deterministic. */
function swPair(order,met,byes){
  const n=order.length,ix=new Map(order.map((k,i)=>[k,i])),M=new Uint8Array(n*n),B=byes||new Set;
  met&&met.forEach(s=>{const k=s.split("|"),i=ix.get(k[0]),j=ix.get(k[1]);null!=i&&null!=j&&i!==j&&(M[i*n+j]=M[j*n+i]=1)});
  let cands=[-1];
  if(n%2){const E=order.map((k,i)=>i).filter(i=>!B.has(order[i]));cands=(E.length?E:order.map((k,i)=>i)).reverse()}
  const without=(L,a,b)=>L.filter(x=>x!==a&&x!==b);
  /* Players left with nobody new to meet: each one costs a rematch. */
  const stuck=L=>{let c=0;for(const x of L){let ok=!1;for(const y of L)if(y!==x&&!M[x*n+y]){ok=!0;break}ok||c++}return c};
  let budget=2e5,hit=!1,found=null,bye=-1;
  const dfs=L=>{
    if(!L.length)return[];
    if(--budget<0){hit=!0;return null}
    const p=L[0];
    for(let k=1;k<L.length;k++){
      const q=L[k];if(M[p*n+q])continue;
      const R=without(L,p,q);if(stuck(R))continue;
      const s=dfs(R);if(s){s.unshift([p,q]);return s}
      if(hit)return null;
    }
    return null;
  };
  for(const c of cands){const s=dfs(without(order.map((k,i)=>i),c,-2));if(s){found=s;bye=c;break}if(hit)break}
  let re=0;
  if(!found){
    /* Branch and bound on the number of rematches, unmet partners first, so
       the first answer is the greedy one and later ones only improve on it. */
    const lb=hit?0:1;let b2=2e5,best=null,bc=1/0;
    const bnb=(L,c,acc)=>{
      if(!L.length){if(c<bc){bc=c;best=acc.slice()}return}
      if(c+Math.ceil(stuck(L)/2)>=bc)return;
      if(--b2<0&&best)return;
      const p=L[0],qs=L.slice(1),Q=qs.filter(q=>!M[p*n+q]).concat(qs.filter(q=>M[p*n+q]));
      for(const q of Q){acc.push([p,q]);bnb(without(L,p,q),c+M[p*n+q],acc);acc.pop();if(bc<=lb||b2<0&&best)return}
    };
    for(const c of cands){const pb=bc;bnb(without(order.map((k,i)=>i),c,-2),0,[]);bc<pb&&(found=best,bye=c);if(bc<=lb||b2<0)break}
    re=bc;
  }
  const pairs=found.map(x=>[order[x[0]],order[x[1]]]);
  bye>=0&&pairs.push([order[bye],null]);
  return{pairs,bye:bye>=0?order[bye]:null,rematches:re,exhaustive:!hit};
}
/* Round 1 is random (the Guide's recommendation), but from a stored seed, so
   the same tournament always gives the same round 1. */
function swPairRound1(keys,seed){const s=swPair(swShuffle(keys,seed>>>0),new Set,new Set);s.round=1;return s}
/* The pairing of the next round: round 1 from the seed, then by standings. */
function swNextPairs(p){
  const r=swCur(p)+1;
  if(1===r)return swPairRound1(swActive(p),p.seed>>>0);
  const s=swPair(swOrder(p),swMet(p),swByes(p));s.round=r;return s;
}
/* Automation. The tournament-auto Edge Function runs this same block (copied
   by tools/sync-swiss-engine.sh) on the stored payload, so no phone chooses
   the pairings. payload.hold.pair = N pauses the automatic pairing of round
   N (set when the organizer undoes it); payload.hold.close stops the
   automatic close (set by Reopen). swCloseRows is what t_close and
   t_auto_close take as the final standings. */
function swCloseRows(p){return swTable(p).map(r=>({id:r.id,rk:r.rk,tp:r.tp,w:r.w,d:r.d,l:r.l,md:r.md,sos:r.sos,drop:r.drop}))}
/* What is due once a round is complete: "pair", "close" or null. */
function swAutoDue(p){
  if(!swIsSwiss(p)||!swRoundDone(p))return null;
  const cur=swCur(p),R=p.rounds|0,h=p.hold||{};
  if(cur<R&&swActive(p).length>=2)return h.pair===cur+1?null:"pair";
  return h.close?null:"close";
}
function swAutoStep(p){
  const k=swAutoDue(p);
  if("pair"===k){const s=swNextPairs(p);return{kind:"pair",round:s.round,pairs:s.pairs,rematch:s.rematches>0}}
  return"close"===k?{kind:"close",standings:swCloseRows(p)}:{kind:"none"};
}
