// @ts-nocheck: the Swiss engine below is the site's plain JavaScript, copied
// byte for byte from index.html, so this file is not type-checked.
//
// Supabase Edge Function "tournament-auto" for Seekers League.
//
// Pairs the next round of a running Swiss tournament as soon as every result
// of the current round is in, and closes the tournament after the last result
// of the last round. Any participant's page or phone asks for it ("check this
// tournament"); nobody chooses the pairings: this function computes them with
// the same Swiss engine as the organizer's page, and the service-role RPCs
// t_auto_pair and t_auto_close lock the row, check its rev and round, validate
// and write. Concurrent asks are safe: one wins, the others get 'stale', read
// again and find nothing left to do.
//
//   POST { "tid": "<tournament uuid>" }
//
// Answers (always HTTP 200 with JSON, except OPTIONS and wrong methods):
//   { "ok": true,  "did": "paired", "round": <n>, "rev": <n> }
//   { "ok": true,  "did": "closed", "rev": <n>, "champion": "<key>" | null }
//   { "ok": true,  "did": "none", "why"?: "<reason>" }   nothing to do (yet)
//   { "ok": false, "reason": "not_allowed" | "rate_limited" | "error" }
//
// The caller must be signed in (not anonymous) and be the tournament's
// organizer or a player of it with a linked account who has not dropped
// (t_auto_allow, asked as the caller). The tournament is read and written
// with the service role only after that. t_auto_allow also brakes: 60 asks
// an hour per account and 3000 on the site ("rate_limited").
//
// "Verify JWT" is turned off for this function in the dashboard: the code
// below verifies the user itself (auth.getUser), like play-network-event.
//
// Never edit the block between the SWISS ENGINE markers by hand: run
//   sh tools/sync-swiss-engine.sh
// after any change to the engine in index.html, then paste this file again.
// "sh tools/sync-swiss-engine.sh --check" tells whether it is in sync.
// Logs carry short error codes only, never payloads, names or tokens.

