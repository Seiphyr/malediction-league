const CLIENT_OPTIONS = { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } };
const service = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, CLIENT_OPTIONS);

Deno.serve(async (req: Request) => {
  const cors = corsHeaders(req.headers.get("origin"));
  if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
  if (req.method !== "POST") return reply({ ok: false, reason: "bad_request" }, cors, 405);

  try {
    // 1. A signed-in user. The anon key alone is not a user.
    const token = /^Bearer\s+(\S{20,8192})$/i.exec(req.headers.get("authorization") ?? "")?.[1];
    if (!token) return reply(NOT_ALLOWED, cors);
    const caller = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
      ...CLIENT_OPTIONS,
      global: { headers: { Authorization: `Bearer ${token}` } },
    });
    const { data: auth, error: authErr } = await caller.auth.getUser(token);
    const user = auth?.user;
    if (authErr || !user || user.is_anonymous) return reply(NOT_ALLOWED, cors);

    // 2. The request: { tid }.
    const body = await readRequestJson(req);
    const tid = body && typeof body.tid === "string" && UUID.test(body.tid) ? body.tid : null;
    if (!tid) return reply(NOT_ALLOWED, cors);

    // 3. The organizer, or a player of this running Swiss tournament (linked
    //    account, not dropped), asked as the caller.
    const allow = await caller.rpc("t_auto_allow", { p_tid: tid });
    if (allow.error) {
      console.error("tournament-auto: t_auto_allow failed", allow.error.code ?? "");
      return reply(ERROR, cors);
    }
    const a = (allow.data && typeof allow.data === "object" ? allow.data : {}) as Json;
    if (a.ok !== true) return reply(a.reason === "rate_limited" ? RATE_LIMITED : NOT_ALLOWED, cors);

    // 4. Read, compute, write. A 'stale' answer means someone else changed the
    //    tournament in between (another phone, or the organizer): read again.
    for (let attempt = 0; attempt < ATTEMPTS; attempt++) {
      const { data: t, error } = await service.from("tournaments").select("id, rev, status, payload").eq("id", tid).maybeSingle();
      if (error) {
        console.error("tournament-auto: read failed", error.code ?? "");
        return reply(ERROR, cors);
      }
      if (!t || t.status !== "running") return reply({ ok: true, did: "none" }, cors);
      const rev = Number(t.rev) | 0;
      const st = swAutoStep(t.payload);
      if (st.kind === "none") return reply({ ok: true, did: "none" }, cors);

      const res = st.kind === "pair"
        ? await service.rpc("t_auto_pair", { p_tid: tid, p_rev: rev, p_round: st.round, p_pairs: st.pairs, p_rematch: st.rematch })
        : await service.rpc("t_auto_close", { p_tid: tid, p_rev: rev, p_standings: st.standings });
      if (res.error) {
        console.error("tournament-auto: " + (st.kind === "pair" ? "t_auto_pair" : "t_auto_close") + " failed", res.error.code ?? "");
        return reply(ERROR, cors);
      }
      const r = (res.data && typeof res.data === "object" ? res.data : {}) as Json;
      if (r.ok === true) {
        return reply(
          st.kind === "pair"
            ? { ok: true, did: "paired", round: st.round, rev: Number(r.rev) | 0 }
            : { ok: true, did: "closed", rev: Number(r.rev) | 0, champion: typeof r.champion === "string" ? r.champion : null },
          cors,
        );
      }
      const why = typeof r.reason === "string" ? r.reason.slice(0, 40) : "refused";
      if (why === "stale") continue;
      // hold, not_done, rounds_done, status: nothing to do. bad_pairs would
      // mean the engine and the SQL rules disagree: worth a log line.
      if (why === "bad_pairs" || why === "refused") console.error("tournament-auto: refused", why);
      return reply({ ok: true, did: "none", why }, cors);
    }
    return reply({ ok: true, did: "none", why: "stale" }, cors);
  } catch (e) {
    console.error("tournament-auto: error", e instanceof Error ? e.name : "unknown");
    return reply(ERROR, cors);
  }
});
